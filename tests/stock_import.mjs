import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const context={TextDecoder,Uint8Array,ArrayBuffer,Buffer,console};context.window=context;
vm.createContext(context);
vm.runInContext(await readFile(new URL('../server/admin/vendor/xlsx.full.min.js',import.meta.url),'utf8'),context);
vm.runInContext(await readFile(new URL('../server/admin/stock-import.js',import.meta.url),'utf8'),context);
const X=context.XLSX;
const sheet=X.utils.aoa_to_sheet([['Артикул','Наименование'],['001234','Фильтр масляный'],[123,'Болт'],['1E123','Уплотнение']]);sheet.A3.z='000000';
const wb=X.utils.book_new();X.utils.book_append_sheet(wb,sheet,'Склад');
const bytes=X.write(wb,{bookType:'xlsx',type:'array'});
const csv=await context.SP49_readStockFile({name:'stock.xlsx',size:bytes.byteLength,arrayBuffer:async()=>bytes});
assert.ok(csv.includes('001234;Фильтр масляный'));
assert.ok(csv.includes('000123;Болт'));
assert.ok(csv.includes('1E123;Уплотнение'));
const utf8=new TextEncoder().encode('Артикул;Наименование\n0001;Гайка\n');
assert.ok((await context.SP49_readStockFile({name:'stock.csv',size:utf8.byteLength,arrayBuffer:async()=>utf8.buffer})).includes('0001;Гайка'));
await assert.rejects(()=>context.SP49_readStockFile({name:'big.xlsx',size:6*1024*1024}),/5 МБ/);
const warehouseWorkbook=X.utils.book_new();
const warehouseRows=Array.from({length:8296},(_,i)=>['SKU-'+i,'Запчасть '+i]);
X.utils.book_append_sheet(warehouseWorkbook,X.utils.aoa_to_sheet(warehouseRows),'Склад');
const warehouseBytes=X.write(warehouseWorkbook,{bookType:'xlsx',type:'array'});
const warehouseFile={name:'warehouse.xlsx',size:warehouseBytes.byteLength,arrayBuffer:async()=>warehouseBytes};
const warehouseCsv=await context.SP49_readStockFile(warehouseFile,{headerless:true});
const lines=warehouseCsv.split('\n');
assert.equal(lines.length,8297);
assert.deepEqual(lines.slice(0,2),['Артикул;Наименование','SKU-0;Запчасть 0']);
assert.equal(lines.at(-1),'SKU-8295;Запчасть 8295');
console.log('Excel/CSV reader: text articles, number formatting, UTF-8, size limit and full headerless warehouse passed.');
